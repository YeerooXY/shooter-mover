"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const repo = path.resolve(process.argv[2] || path.join(__dirname, "..", ".."));
const sources = [
  { kind: "gun-family", schema: "shooter-mover.gun-family/1", dir: "Content/Items/Guns", suffix: ".gun.json" },
  { kind: "gear-set", schema: "shooter-mover.gear-set/1", dir: "Content/Items/Gear", suffix: ".gear.json" }
];
const output = path.join(repo, "Assets/ShooterMover/Runtime/Application/Items/Generated/ItemPackageSources.g.cs");

function fail(message) { throw new Error(message); }
function stableId(value) { return /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(value); }
const entries = [];
for (const source of sources) {
  const folder = path.join(repo, source.dir);
  if (!fs.existsSync(folder)) continue;
  for (const file of fs.readdirSync(folder).filter(name => name.endsWith(source.suffix)).sort()) {
    const full = path.join(folder, file);
    const raw = fs.readFileSync(full, "utf8");
    let value;
    try { value = JSON.parse(raw); } catch (error) { fail(`${source.dir}/${file}: malformed JSON: ${error.message}`); }
    if (value.$schema !== source.schema || value.kind !== source.kind) fail(`${source.dir}/${file}: schema/kind mismatch`);
    if (!stableId(value.id) || !value.name || !Array.isArray(value.marks) || value.marks.length !== 3
        || value.marks.some((mark, index) => !mark || mark.mark !== index + 1)) fail(`${source.dir}/${file}: invalid identity or marks`);
    if (source.kind === "gun-family" && (!value.fire || !value.shot || !value.delivery || !value.rarity || !value.damageType)) fail(`${source.dir}/${file}: gun behavior is incomplete`);
    if (source.kind === "gear-set" && value.marks.some(mark => !mark.pieces || ["headpiece", "body-armor", "legs", "boots"].some(slot => !mark.pieces[slot]))) fail(`${source.dir}/${file}: gear set is missing a required piece`);
    if (entries.some(entry => entry.kind === source.kind && entry.id === value.id)) fail(`Duplicate ${source.kind} ID: ${value.id}`);
    entries.push({ kind: source.kind, id: value.id, json: JSON.stringify(value), file: `${source.dir}/${file}`.replace(/\\/g, "/") });
  }
}
entries.sort((a, b) => `${a.kind}:${a.id}`.localeCompare(`${b.kind}:${b.id}`));
const fingerprint = crypto.createHash("sha256").update(entries.map(x => `${x.file}\n${x.json}\n`).join("")).digest("hex");
const literals = entries.map(entry =>
  `            new ItemPackageSource("${entry.kind}", "${entry.id}", "${entry.file}", Convert.FromBase64String("${Buffer.from(entry.json).toString("base64")}")),`
).join("\n");
const csharp = `// <auto-generated />\nusing System;\nusing System.Collections.Generic;\nusing System.Text;\n\nnamespace ShooterMover.Application.Items.Generated\n{\n    public sealed class ItemPackageSource\n    {\n        internal ItemPackageSource(string kind, string id, string path, byte[] json)\n        {\n            Kind = kind; Id = id; SourcePath = path; Json = Encoding.UTF8.GetString(json);\n        }\n        public string Kind { get; }\n        public string Id { get; }\n        public string SourcePath { get; }\n        public string Json { get; }\n    }\n\n    public static class ItemPackageSources\n    {\n        public const string Fingerprint = "${fingerprint}";\n        private static readonly ItemPackageSource[] values = new ItemPackageSource[]\n        {\n${literals}\n        };\n        public static IReadOnlyList<ItemPackageSource> All { get { return values; } }\n    }\n}\n`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, csharp.replace(/\r?\n/g, "\n"));
console.log(`Compiled ${entries.length} item package(s); fingerprint ${fingerprint}.`);
